/** Forventede slag fra 'lengde' meter med gitt lie (fairway er default). */
export function sgFraLengde(meter: number | null, lie: LieKode | LieNavn | null | undefined): number | null {
  if (meter == null) return null;
  const navn = (lie && lie in LIE_KODE_TIL_NAVN ? LIE_KODE_TIL_NAVN[lie as LieKode] : (lie as LieNavn)) || "fairway";
  const tabell = SG_ETTER_LIE[navn] ?? SG_ETTER_LIE.fairway;
  return slaOpp(tabell, meter);
}

/** Forventede putter fra avstand (grov tabell — brukes i banetester og puttetester). */
export function forventedePutter(meter: number | null): number | null {
  return slaOpp(FORVENTEDE_PUTTER_GROV, meter);
}

